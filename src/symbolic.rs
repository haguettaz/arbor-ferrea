//! Structural analysis and symbolic elimination trees for factor graphs.
//!
//! Simulates variable elimination to determine graph chordal completion, factor
//! assignments, separator sets, and elimination tree topology prior to numerical solves.

use std::collections::{HashMap, HashSet};
use std::fmt::{Display, Formatter, Result as FmtResult};

use crate::gaussian::GaussianFactor;

/// A clique in a symbolic elimination tree representing an elimination clique.
pub struct SymbolicClique {
    /// Variable eliminated at this node.
    pub front_key: usize,
    /// Separator variables conditioning this node during elimination.
    pub sep_keys: HashSet<usize>,
    /// Indices of original factors assigned to this node.
    pub factors: Vec<usize>,
    /// Child nodes in the elimination tree.
    pub children: Vec<SymbolicClique>,
}

/// An elimination tree forest capturing the factorization topology.
pub struct SymbolicTree {
    /// Root nodes of independent elimination trees in the forest.
    pub roots: Vec<SymbolicClique>,
}

impl SymbolicTree {
    /// Constructs a symbolic elimination tree from factors and an elimination ordering.
    ///
    /// The caller must ensure that the keys provided in the elimination order has no duplicate
    /// and cover all variables appearing in the factors.
    pub(crate) fn build(factors: &[GaussianFactor], order: &[usize]) -> Self {
        // Map each variable to its elimination rank: O(1) lookups
        let ranks: HashMap<usize, usize> = order.iter().enumerate().map(|(r, &v)| (v, r)).collect();

        let mut roots: Vec<usize> = Vec::new();
        let mut children_map: HashMap<usize, Vec<usize>> = HashMap::with_capacity(order.len());
        let mut factors_map: HashMap<usize, Vec<usize>> = HashMap::with_capacity(order.len());
        let mut separator_map: HashMap<usize, HashSet<usize>> = HashMap::with_capacity(order.len());

        for (i, factor) in factors.iter().enumerate() {
            // Assign each original factor to the variable in it that is eliminated FIRST
            if let Some(&front_key) = factor.keys().iter().min_by_key(|v| ranks.get(v).unwrap()) {
                factors_map.entry(front_key).or_default().push(i);
                let sep_set = separator_map.entry(front_key).or_default();
                sep_set.extend(factor.keys());
            }
        }

        // Tracks the symbolic fill-in messages generated by eliminated variables.
        // Stored as (front_key, sep_keys).
        let mut active_messages: Vec<(usize, HashSet<usize>)> = Vec::new();

        // Simulate variable elimination
        for front_key in order.iter() {
            // let mut sep_set = HashSet::new();

            // // Get original factors assigned to this variable
            // let assigned_factors = factors_map.get(&var).cloned().unwrap_or_default();
            // for &id in &assigned_factors {
            //     sep_set.extend(factors[i].keys());
            // }

            // Find and extract all active messages that involve the current variable
            let (front_messages, rem_messages): (Vec<_>, Vec<_>) = active_messages
                .into_iter()
                .partition(|(_, keys)| keys.contains(&front_key));

            active_messages = rem_messages;

            let sep_set = separator_map.entry(*front_key).or_default();
            for (_, front_msg) in &front_messages {
                sep_set.extend(front_msg)
            }

            // Remove the frontal variable from the separator set
            sep_set.remove(front_key);

            // let sep_vec: Vec<usize> = sep_set.into_iter().collect();

            // The parent in the tree is the variable in the separator eliminated earliest
            match sep_set
                .iter()
                .min_by_key(|v| ranks.get(v).unwrap())
                .copied()
            {
                Some(parent) => {
                    children_map.entry(parent).or_default().push(*front_key);
                    active_messages.push((*front_key, sep_set.clone()));
                }
                None => {
                    roots.push(*front_key);
                }
            }
        }

        // Assemble the tree nodes recursively using the computed topology
        let root_nodes = roots
            .into_iter()
            .map(|root_var| Self::build_node(root_var, &children_map, &separator_map, &factors_map))
            .collect();

        Self { roots: root_nodes }
    }

    /// Recursively instantiates a [`SymbolicClique`] and its subtree from topology maps.
    fn build_node(
        front_key: usize,
        children_map: &HashMap<usize, Vec<usize>>,
        separator_map: &HashMap<usize, HashSet<usize>>,
        factors_map: &HashMap<usize, Vec<usize>>,
    ) -> SymbolicClique {
        let children = children_map
            .get(&front_key)
            .unwrap_or(&vec![])
            .iter()
            .map(|&child_var| Self::build_node(child_var, children_map, separator_map, factors_map))
            .collect();

        SymbolicClique {
            front_key,
            sep_keys: separator_map.get(&front_key).cloned().unwrap_or_default(),
            factors: factors_map.get(&front_key).cloned().unwrap_or_default(),
            children,
        }
    }
}

impl Display for SymbolicTree {
    fn fmt(&self, f: &mut Formatter<'_>) -> FmtResult {
        if self.roots.is_empty() {
            return write!(f, "Empty SymbolicTree");
        }

        for (i, root) in self.roots.iter().enumerate() {
            // Print the root node
            writeln!(
                f,
                "Root [Var: {}, Factors: {:?}, Separator: {:?}]",
                root.front_key, root.factors, root.sep_keys
            )?;

            // Print all children recursively
            let num_children = root.children.len();
            for (j, child) in root.children.iter().enumerate() {
                child.fmt_recursive(f, "", j == num_children - 1)?;
            }

            // Add a blank line between multiple roots
            if i < self.roots.len() - 1 {
                writeln!(f)?;
            }
        }
        Ok(())
    }
}

impl SymbolicClique {
    /// Recursively formats the node hierarchy as an ASCII tree.
    fn fmt_recursive(&self, f: &mut Formatter<'_>, prefix: &str, is_last: bool) -> FmtResult {
        let branch_marker = if is_last { "└── " } else { "├── " };

        writeln!(
            f,
            "{}{}[Frontal: {}, Separator: {:?}]",
            prefix, branch_marker, self.front_key, self.sep_keys
        )?;

        let child_prefix = format!("{}{}", prefix, if is_last { "    " } else { "│   " });
        let num_children = self.children.len();

        for (i, child) in self.children.iter().enumerate() {
            child.fmt_recursive(f, &child_prefix, i == num_children - 1)?;
        }

        Ok(())
    }
}
